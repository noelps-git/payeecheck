"""
benchmark_pipeline.py — End-to-end PayeeCheck pipeline benchmark.

Runs the full Risk Scorer (which itself runs all Phase 1 signal modules)
against the synthetic dataset generated by data/generate_dataset.py, and
reports real precision/recall/F1/AUPRC — the same evaluation rigor
SCAFDS uses (Section IV.C), at PayeeCheck's UPI-transaction scale.

HONEST NOTE: ground truth here is synthetic (rule-generated), not real
fraud outcomes. These numbers measure "does the pipeline correctly
recover the patterns we deliberately encoded" — a pipeline correctness
check, not a real-world accuracy claim. See generate_dataset.py's
module docstring.

Run:
    python tests/benchmark_pipeline.py --data data/synthetic_transactions.csv
"""
import sys
import os
import csv
import argparse
import json
from datetime import datetime

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from risk_engine.risk_scorer import score_transaction


def load_transactions(csv_path: str) -> list:
    transactions = []
    with open(csv_path, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            row["amount"] = float(row["amount"])
            row["vpa_age_days"] = int(row["vpa_age_days"])
            row["prior_tx_count"] = int(row["prior_tx_count"])
            row["unique_senders_7d"] = int(row["unique_senders_7d"])
            row["mule_flagged"] = row["mule_flagged"] == "True"
            row["mule_flag_count"] = int(row["mule_flag_count"])
            row["is_lookalike"] = row["is_lookalike"] == "True"
            row["name_score"] = float(row["name_score"])
            transactions.append(row)
    return transactions


def compute_metrics(results: list) -> dict:
    """
    Binary framing: is_fraud = label in {mule, lookalike}.
    name_mismatch is treated as ambiguous/excluded from the binary
    fraud metric (matches the playbooks' framing of it as a soft-friction
    signal, not a hard fraud/clean binary).
    """
    fraud_labels = {"mule", "lookalike"}
    clean_labels = {"clean"}

    binary_results = [
        r for r in results if r["true_label"] in fraud_labels | clean_labels
    ]

    tp = fp = tn = fn = 0
    for r in binary_results:
        actual_fraud = r["true_label"] in fraud_labels
        predicted_fraud = r["verdict"] in ("block", "warn")

        if actual_fraud and predicted_fraud:
            tp += 1
        elif actual_fraud and not predicted_fraud:
            fn += 1
        elif not actual_fraud and predicted_fraud:
            fp += 1
        else:
            tn += 1

    precision = tp / (tp + fp) if (tp + fp) else 0
    recall = tp / (tp + fn) if (tp + fn) else 0
    f1 = (2 * precision * recall / (precision + recall)
          if (precision + recall) else 0)

    # AUPRC approximation via risk_score ranking (since we don't have
    # continuous probability outputs across all thresholds, we use the
    # risk_score itself as the ranking signal — standard AUPRC computation)
    sorted_by_score = sorted(
        binary_results, key=lambda r: r["risk_score"], reverse=True
    )
    total_positives = sum(
        1 for r in binary_results if r["true_label"] in fraud_labels
    )

    precisions, recalls = [], []
    tp_running = 0
    for i, r in enumerate(sorted_by_score, 1):
        if r["true_label"] in fraud_labels:
            tp_running += 1
        precisions.append(tp_running / i)
        recalls.append(tp_running / total_positives if total_positives else 0)

    # Trapezoidal AUPRC approximation
    auprc = 0.0
    for i in range(1, len(recalls)):
        auprc += (recalls[i] - recalls[i-1]) * (precisions[i] + precisions[i-1]) / 2

    return {
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "auprc_approx": round(abs(auprc), 4),
        "n_binary_cases": len(binary_results),
    }


def compute_per_category_breakdown(results: list) -> dict:
    """How well does the pipeline distinguish each fraud TYPE specifically?"""
    by_label = {}
    for r in results:
        label = r["true_label"]
        by_label.setdefault(label, {"total": 0, "blocked": 0, "warned": 0, "passed": 0})
        by_label[label]["total"] += 1
        by_label[label][{"block": "blocked", "warn": "warned",
                          "pass": "passed"}[r["verdict"]]] += 1
    return by_label


def compute_signal_contribution(results: list) -> dict:
    """Which Phase 1 signals fired most often, and on what label distribution?"""
    signal_counts = {}
    for r in results:
        for layer in ("L1", "L2", "L3"):
            for sig in r["attribution"][layer]:
                name = sig["signal"]
                signal_counts.setdefault(name, {"total_fired": 0, "by_label": {}})
                signal_counts[name]["total_fired"] += 1
                label = r["true_label"]
                signal_counts[name]["by_label"][label] = (
                    signal_counts[name]["by_label"].get(label, 0) + 1
                )
    return signal_counts


def run_benchmark(csv_path: str, output_json: str = None):
    print(f"Loading transactions from {csv_path}...")
    transactions = load_transactions(csv_path)
    print(f"Loaded {len(transactions)} transactions. Scoring through full pipeline...\n")

    results = []
    t0 = datetime.now()
    for i, tx in enumerate(transactions):
        if i % 100 == 0:
            print(f"  Scored {i}/{len(transactions)}...")
        results.append(score_transaction(tx))
    elapsed = (datetime.now() - t0).total_seconds()

    print(f"\nScored {len(results)} transactions in {elapsed:.1f}s "
          f"({elapsed/len(results)*1000:.1f}ms/tx average)\n")

    metrics = compute_metrics(results)
    breakdown = compute_per_category_breakdown(results)
    signal_contribution = compute_signal_contribution(results)

    print("=" * 70)
    print("  OVERALL BINARY METRICS (fraud = mule | lookalike)")
    print("=" * 70)
    for k, v in metrics.items():
        print(f"  {k}: {v}")

    print(f"\n{'='*70}")
    print("  PER-CATEGORY VERDICT BREAKDOWN")
    print(f"{'='*70}")
    print(f"  {'Label':<15}{'Total':<8}{'Blocked':<10}{'Warned':<10}{'Passed':<8}")
    for label, counts in breakdown.items():
        print(f"  {label:<15}{counts['total']:<8}{counts['blocked']:<10}"
              f"{counts['warned']:<10}{counts['passed']:<8}")

    print(f"\n{'='*70}")
    print("  SIGNAL FIRING FREQUENCY (which signals contributed most)")
    print(f"{'='*70}")
    sorted_signals = sorted(signal_contribution.items(),
                             key=lambda x: x[1]["total_fired"], reverse=True)
    for name, data in sorted_signals:
        print(f"  {name:<25}{data['total_fired']:<10}{data['by_label']}")

    full_report = {
        "elapsed_seconds": elapsed,
        "metrics": metrics,
        "category_breakdown": breakdown,
        "signal_contribution": signal_contribution,
    }

    if output_json:
        with open(output_json, "w") as f:
            json.dump(full_report, f, indent=2, default=str)
        print(f"\nFull report saved to {output_json}")

    return full_report


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=str,
                        default="data/synthetic_transactions.csv")
    parser.add_argument("--out", type=str,
                        default="data/benchmark_report.json")
    args = parser.parse_args()

    run_benchmark(args.data, args.out)
